CREATE TABLE endereco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado VARCHAR(100),
    cidade VARCHAR(100) NOT NULL,
    bairro VARCHAR(100),
    rua VARCHAR(150) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    codigo_postal VARCHAR(8),
    informacoes_adicionais VARCHAR(255)
);
CREATE TABLE cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    nome_social VARCHAR(150),
    data_nascimento DATE NOT NULL,
    data_cadastro TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    endereco_id BIGINT UNIQUE REFERENCES endereco(id)
);
CREATE TABLE documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(30) NOT NULL,
    numero VARCHAR(50) NOT NULL,
    cliente_id BIGINT REFERENCES cliente(id),
    CONSTRAINT uk_documento_numero UNIQUE(numero)
);
CREATE TABLE telefone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ddd VARCHAR(2) NOT NULL,
    numero VARCHAR(9) NOT NULL,
    cliente_id BIGINT REFERENCES cliente(id),
    CONSTRAINT uk_telefone_cliente UNIQUE(cliente_id, ddd, numero)
);
CREATE INDEX ix_documento_cliente ON documento(cliente_id);
CREATE INDEX ix_telefone_cliente ON telefone(cliente_id);
